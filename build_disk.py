B = ROOT / ".build"; TOOLS = B / "tools"
DIST = ROOT / "dist"
WORK = B / "disk"; SYS_STAGE = WORK / "sysroot"; LOADER = WORK / "loader"
ESP_FILES = WORK / "esp_files"; INT_STAGE = WORK / "integrity"; DATA_STAGE = WORK / "data"
SECTOR = 512
MIB = 1024 * 1024

sys.path.insert(0, str(ROOT))
