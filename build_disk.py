#!/usr/bin/env python3
"""
NeurAI installed-system disk image builder.
Produces two GPT disk images implementing roadmap/deployment-host.md:
  neurai-system-2.0.0.img : biosboot + ESP + NEURAI_ROOT + NEURAI_INTEGRITY + swap
  neurai-data-2.0.0.img   : NEURAI_DATA (models, home, artifacts, spawns, logs)
Boot chain: GRUB (UEFI BOOTX64.EFI on ESP, BIOS core.img fallback) ->
kernel + small loader initramfs -> marker-probe partitions -> switch_root
-> disk system init -> NeurAI. No ISO toolchain required: FAT32 and GPT
are written by this file; ext4 via mke2fs -d.
"""
import os, sys, io, gzip, zlib, uuid, shutil, struct, subprocess
