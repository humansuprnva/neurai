# ---------------------------------------------------------------- modules
def _modinfo_depends(path: Path):
    """Module deps from the .modinfo section (modules.dep is not shipped
    in the Debian linux-image .deb - it is generated by depmod at install)."""
    try: data = path.read_bytes()
    except Exception: return []
    out = []
    for m in __import__("re").finditer(rb"depends=([^\x00]*)", data):
        out += [d.decode(errors="replace") for d in m.group(1).split(b",") if d]
    return out

def _norm(name): return name.replace("-", "_").removesuffix(".ko")

def module_closure():
    kdir = next(p for p in TOOLS.rglob("modules.builtin")).parent
    by_name = {}
    for p in kdir.rglob("*.ko"):
        by_name.setdefault(_norm(p.name), p)
    deps = {}
    def get_deps(norm):
        if norm not in deps:
            deps[norm] = [_norm(d) for d in _modinfo_depends(by_name[norm])] if norm in by_name else []
        return deps[norm]
    roots = ["ext4", "vfat", "nvme", "ahci", "ata_piix", "sd_mod", "sr_mod",
             "virtio_blk", "virtio_pci", "xhci_hcd", "xhci_pci", "ehci_hcd",
             "usbhid", "hid_generic",
             # soft deps not in modinfo depends=: ext4/crypto + vfat NLS
             "crc32c_intel", "libcrc32c", "crc32c_generic", "crc32c",
             "nls_cp437", "nls_iso8859_1", "nls_utf8", "nls_ascii"]
    order, seen = [], set()
    def visit(name):
        n = _norm(name)
        if n in seen or n not in by_name: return
        seen.add(n)
        for d in get_deps(n): visit(d)
        order.append(by_name[n].name)
    for r in roots: visit(r)
    missing = [r for r in roots if _norm(r) not in seen]
    if missing: print("  modules not present (built-in or absent, ok):", missing)
    return order, {_norm(p.name): p for p in by_name.values()}

def build_loader_initrd():
    if LOADER.exists(): shutil.rmtree(LOADER)
    for d in ["bin", "sbin", "usr/bin", "proc", "sys", "dev", "probe", "newroot", "lib/modules"]:
        (LOADER / d).mkdir(parents=True, exist_ok=True)
    busybox = find(["busybox"], TOOLS)
    shutil.copy2(busybox, LOADER / "bin/busybox"); os.chmod(LOADER / "bin/busybox", 0o755)
    applets = subprocess.run([str(LOADER / "bin/busybox"), "--list"], capture_output=True, text=True).stdout.split()
    for ap in applets:
        for d in ["bin", "sbin", "usr/bin"]:
            link = LOADER / d / ap
            if not link.exists() and not link.is_symlink():
                link.parent.mkdir(parents=True, exist_ok=True)
                try: os.symlink("/bin/busybox", link)
                except FileExistsError: pass
                break
    # Kernel request_module() calls /sbin/modprobe - make sure it exists
    mp = LOADER / "sbin/modprobe"
    if not mp.exists() and not mp.is_symlink():
        try: mp.symlink_to("/bin/busybox")
        except FileExistsError: pass
    order, by_name = module_closure()
    for fname in order: shutil.copy2(by_name[_norm(fname)], LOADER / "lib/modules" / fname)
    (LOADER / "lib/modules/order.txt").write_text("\n".join(order) + "\n")
    print("  loader modules:", len(order))
    shutil.copy2(ROOT / "rootfs/init-disk-loader", LOADER / "init"); os.chmod(LOADER / "init", 0o755)
    raw = cpio_newc(LOADER)
    dest = WORK / "initrd.gz"
    with open(dest, "wb") as f:
        with gzip.GzipFile(filename="", mode="wb", fileobj=f, compresslevel=1, mtime=0) as g: g.write(raw)
    print("  loader initrd.gz:", dest.stat().st_size // 1048576, "MB")
    return dest

# ---------------------------------------------------------------- staging
def build_sysroot():
    src = B / "rootfs"
    if not (src / "usr/local/lib/neurai/neurai.py").exists():
        raise SystemExit("run build_iso.py first (need .build/rootfs)")
    core = (src / "usr/local/lib/neurai/neurai.py").read_text()
    print("  neurai.py has autonomy-LLM gate:", "NEURAI_AUTONOMY_LLM" in core)
    if SYS_STAGE.exists(): shutil.rmtree(SYS_STAGE)
    def ignore(dirpath, names):
        rel = str(Path(dirpath).relative_to(src))
        drop = []
        for n in names:
            if rel == "usr/local/lib/neurai" and n == "models": drop.append(n)
            if rel == "." and n == "init": drop.append(n)
            if rel == "tmp" or rel == "var/lib/neurai": drop.append(n)
        return drop
    shutil.copytree(src, SYS_STAGE, ignore=ignore, symlinks=True)
    (SYS_STAGE / "sbin").mkdir(exist_ok=True)
    shutil.copy2(ROOT / "rootfs/init-disk-system", SYS_STAGE / "sbin/init"); os.chmod(SYS_STAGE / "sbin/init", 0o755)
    for d in ["neurai/data", "neurai/integrity", "boot/efi", "var/lib/neurai", "tmp"]:
        (SYS_STAGE / d).mkdir(parents=True, exist_ok=True)
    (SYS_STAGE / "etc/neurai-release").write_text("role=root\nversion=2.0.0\nlayout=installed-2drive\n")
    print("  sysroot staged:", sum(f.stat().st_size for f in SYS_STAGE.rglob('*') if f.is_file()) // 1048576, "MB")

